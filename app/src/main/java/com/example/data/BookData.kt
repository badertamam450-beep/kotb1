    fun searchBook(query: String): List<Pair<Chapter, String>> {
        if (query.isBlank()) return emptyList()
        val cleanQuery = query.trim()
        val results = mutableListOf<Pair<Chapter, String>>()

        for (chapter in allChapters) {
            if (chapter.title.contains(cleanQuery, ignoreCase = true) ||
                chapter.subtitle.contains(cleanQuery, ignoreCase = true)
            ) {
                results.add(chapter to "تطابق في عنوان الفصل: ${chapter.title}")
            }

            for (block in chapter.content) {
                when (block) {
                    is ContentBlock.Paragraph -> {
                        if (block.text.contains(cleanQuery, ignoreCase = true)) {
                            results.add(chapter to block.text)
                        }
                    }
                    is ContentBlock.Highlight -> {
                        if (block.text.contains(cleanQuery, ignoreCase = true)) {
                            results.add(chapter to block.text)
                        }
                    }
                    is ContentBlock.Quote -> {
                        if (block.text.contains(cleanQuery, ignoreCase = true)) {
                            results.add(chapter to block.text)
                        }
                    }
                    is ContentBlock.Subheading -> {
                        if (block.text.contains(cleanQuery, ignoreCase = true)) {
                            results.add(chapter to block.text)
                        }
                    }
                    is ContentBlock.BulletList -> {
                        for (item in block.items) {
                            if (item.contains(cleanQuery, ignoreCase = true)) {
                                results.add(chapter to item)
                            }
                        }
                    }
                    is ContentBlock.Verse -> {
                        if (block.text.contains(cleanQuery, ignoreCase = true) ||
                            block.surah.contains(cleanQuery, ignoreCase = true)
                        ) {
                            results.add(chapter to "آية قرانية (${block.surah}): ${block.text}")
                        }
                    }
                }
            }

            for (verse in chapter.quranVerses) {
                if (verse.text.contains(cleanQuery, ignoreCase = true) ||
                    verse.surah.contains(cleanQuery, ignoreCase = true)
                ) {
                    results.add(chapter to "شاهد قرآني [سورة ${verse.surah}]: ${verse.text}")
                }
            }
        }
        return results.distinctBy { it.first.id to it.second.take(40) }
    }
